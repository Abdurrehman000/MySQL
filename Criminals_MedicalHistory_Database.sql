-- ==========================================
-- Criminal & Medical Management Database
-- Clean, Single-File Execution Script
-- ==========================================

CREATE DATABASE IF NOT EXISTS Criminal_Medical_DB;
USE Criminal_Medical_DB;

-- ==========================================
-- 1. PARENT TABLES (No dependencies)
-- ==========================================

CREATE TABLE Criminals (
    criminal_id INT AUTO_INCREMENT PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    age INT,
    gender VARCHAR(10) NOT NULL,
    biometric_id VARCHAR(50) UNIQUE NOT NULL,
    registration_date DATE ,
    current_status VARCHAR(50) DEFAULT 'Under Investigation'
);

CREATE TABLE Cases (
    case_id INT AUTO_INCREMENT PRIMARY KEY,
    case_number VARCHAR(50) UNIQUE NOT NULL,
    crime_type VARCHAR(100) NOT NULL,
    case_details TEXT,
    arrest_date DATE NOT NULL,
    court_name VARCHAR(100),
    judge_name VARCHAR(100),
    lawyer_name VARCHAR(100),
    case_status VARCHAR(50) DEFAULT 'Pending'
);

CREATE TABLE Facilities (
    facility_id INT AUTO_INCREMENT PRIMARY KEY,
    jail_name VARCHAR(100) NOT NULL,
    location VARCHAR(150),
    capacity INT,
    has_medical_unit BOOLEAN DEFAULT TRUE
);

CREATE TABLE Doctors (
    doctor_id INT AUTO_INCREMENT PRIMARY KEY,
    doctor_name VARCHAR(100) NOT NULL,
    specialization VARCHAR(100),
    license_number VARCHAR(50) UNIQUE,
    contact_number VARCHAR(20)
);

-- ==========================================
-- 2. CHILD & JUNCTION TABLES (Depend on parents)
-- ==========================================

CREATE TABLE Criminal_Facility_Assignment (
    assignment_id INT AUTO_INCREMENT PRIMARY KEY,
    criminal_id INT NOT NULL,
    facility_id INT NOT NULL,
    admission_date DATE NOT NULL,
    release_date DATE NULL,
    assignment_status VARCHAR(50) DEFAULT 'Active',
    FOREIGN KEY (criminal_id) REFERENCES Criminals(criminal_id),
    FOREIGN KEY (facility_id) REFERENCES Facilities(facility_id)
);

CREATE TABLE Case_Criminal_Link (
    link_id INT AUTO_INCREMENT PRIMARY KEY,
    case_id INT NOT NULL,
    criminal_id INT NOT NULL,
    involvement_role VARCHAR(50) DEFAULT 'Defendant',
    FOREIGN KEY (case_id) REFERENCES Cases(case_id),
    FOREIGN KEY (criminal_id) REFERENCES Criminals(criminal_id)
);

CREATE TABLE Medical_History (
    history_id INT AUTO_INCREMENT PRIMARY KEY,
    criminal_id INT UNIQUE NOT NULL,
    blood_group VARCHAR(5),
    known_allergies TEXT,
    chronic_diseases TEXT,
    past_conditions TEXT,
    FOREIGN KEY (criminal_id) REFERENCES Criminals(criminal_id)
);

CREATE TABLE Medical_Visits (
    visit_id INT AUTO_INCREMENT PRIMARY KEY,
    criminal_id INT NOT NULL,
    doctor_id INT NOT NULL,
    visit_date DATE,
    diagnosis TEXT,
    treatment_notes TEXT,
    FOREIGN KEY (criminal_id) REFERENCES Criminals(criminal_id),
    FOREIGN KEY (doctor_id) REFERENCES Doctors(doctor_id)
);

CREATE TABLE Mental_Health_Records (
    mh_record_id INT AUTO_INCREMENT PRIMARY KEY,
    criminal_id INT NOT NULL,
    diagnosis VARCHAR(200),
    evaluation_date DATE,
    evaluation_report TEXT,
    therapy_details TEXT,
    FOREIGN KEY (criminal_id) REFERENCES Criminals(criminal_id)
);

CREATE TABLE Case_Medical_Evidence (
    evidence_id INT AUTO_INCREMENT PRIMARY KEY,
    case_id INT NOT NULL,
    visit_id INT NOT NULL,
    evidence_description TEXT,
    submission_date DATE,
    FOREIGN KEY (case_id) REFERENCES Cases(case_id),
    FOREIGN KEY (visit_id) REFERENCES Medical_Visits(visit_id)
);

CREATE TABLE Prescriptions (
    prescription_id INT AUTO_INCREMENT PRIMARY KEY,
    visit_id INT NOT NULL,
    medicine_name VARCHAR(100) NOT NULL,
    dosage VARCHAR(100) NOT NULL,
    duration_days INT,
    prescribed_by INT NOT NULL,
    prescription_date DATE,
    prescription_status VARCHAR(50) DEFAULT 'Active',
    FOREIGN KEY (visit_id) REFERENCES Medical_Visits(visit_id),
    FOREIGN KEY (prescribed_by) REFERENCES Doctors(doctor_id)
);

